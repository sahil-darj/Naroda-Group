// Enhanced translation system
const TranslationSystem = {
  currentLang: 'en',

  init() {
    // Load saved language or default to English
    this.currentLang = localStorage.getItem('preferredLanguage') || 'en';
    this.apply(this.currentLang);
    this.setupLanguageSwitcher();
    this.setupEventListeners();
  },

  apply(lang) {
    this.currentLang = lang;
    const elements = document.querySelectorAll('[data-i18n]');

    elements.forEach(element => {
      const key = element.getAttribute('data-i18n');
      if (translations[lang] && translations[lang][key]) {
        if (element.hasAttribute('data-html') ||
          element.getAttribute('data-html') === 'true' ||
          element.tagName === 'BUTTON' ||
          element.tagName === 'A' ||
          (element.tagName === 'SPAN' && element.classList.contains('gold-text'))) {
          // Preserve HTML structure for elements with HTML content
          element.innerHTML = translations[lang][key];
        } else {
          element.textContent = translations[lang][key];
        }
      }
    });

    // Update language switcher display
    const langElements = document.querySelectorAll('.language-content[data-i18n="nav.language"]');
    langElements.forEach(el => {
      el.textContent = lang === 'en' ? 'EN' : lang === 'hi' ? 'हिंदी' : 'ગુજરાતી';
    });

    // Update language dropdown active state
    document.querySelectorAll('.language-option').forEach(option => {
      if (option.getAttribute('data-lang') === lang) {
        option.classList.add('active');
      } else {
        option.classList.remove('active');
      }
    });

    // Update direction if needed (for RTL languages)
    if (lang === 'ar' || lang === 'he') {
      document.body.style.direction = 'rtl';
    } else {
      document.body.style.direction = 'ltr';
    }

    // Save to localStorage
    localStorage.setItem('preferredLanguage', lang);

    // Dispatch event for other components
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  },

  setupLanguageSwitcher() {
    const languageToggle = document.getElementById('languageToggle');
    const languageOptions = document.getElementById('languageOptions');

    if (languageToggle && languageOptions) {
      languageToggle.addEventListener('click', (e) => {
        e.stopPropagation();
        languageOptions.classList.toggle('show');
      });

      // Language option selection
      document.querySelectorAll('.language-option').forEach(option => {
        option.addEventListener('click', (e) => {
          e.stopPropagation();
          const lang = option.getAttribute('data-lang');
          this.apply(lang);
          this.showLanguageChangeToast(lang);
          languageOptions.classList.remove('show');
        });
      });

      // Close dropdown when clicking outside
      document.addEventListener('click', () => {
        languageOptions.classList.remove('show');
      });
    }
  },

  setupEventListeners() {
    // Listen for dynamic content that might be loaded later
    const observer = new MutationObserver((mutations) => {
      mutations.forEach((mutation) => {
        if (mutation.addedNodes.length) {
          mutation.addedNodes.forEach((node) => {
            if (node.nodeType === 1) { // Element node
              const elements = node.querySelectorAll ? node.querySelectorAll('[data-i18n]') : [];
              elements.forEach(element => {
                const key = element.getAttribute('data-i18n');
                if (translations[this.currentLang] && translations[this.currentLang][key]) {
                  if (element.hasAttribute('data-html')) {
                    element.innerHTML = translations[this.currentLang][key];
                  } else {
                    element.textContent = translations[this.currentLang][key];
                  }
                }
              });
            }
          });
        }
      });
    });

    observer.observe(document.body, {
      childList: true,
      subtree: true
    });
  },

  showLanguageChangeToast(lang) {
    const messages = {
      en: "Language changed to English",
      hi: "भाषा हिंदी में बदल गई",
      gu: "ભાષા ગુજરાતીમાં બદલાઈ ગઈ"
    };

    // Remove existing toast if present
    const existingToast = document.querySelector('.language-toast');
    if (existingToast) existingToast.remove();

    // Create new toast
    const toast = document.createElement('div');
    toast.className = 'language-toast';
    toast.textContent = messages[lang] || "Language changed";
    toast.style.cssText = `
      position: fixed;
      top: 100px;
      right: 20px;
      background: var(--primary-color);
      color: white;
      padding: 12px 24px;
      border-radius: 8px;
      box-shadow: 0 5px 20px rgba(0,0,0,0.3);
      z-index: 9999;
      animation: slideIn 0.3s ease;
      font-weight: 500;
      border-left: 4px solid var(--secondary-color);
    `;

    document.body.appendChild(toast);

    // Remove toast after 3 seconds
    setTimeout(() => {
      toast.style.animation = 'slideOut 0.3s ease';
      setTimeout(() => toast.remove(), 300);
    }, 3000);
  },

  get(key) {
    return translations[this.currentLang]?.[key] || key;
  }
};

// Initialize when DOM is loaded
document.addEventListener('DOMContentLoaded', () => {
  TranslationSystem.init();

  // Add CSS for toast animations
  const style = document.createElement('style');
  style.textContent = `
    @keyframes slideIn {
      from { transform: translateX(100%); opacity: 0; }
      to { transform: translateX(0); opacity: 1; }
    }
    @keyframes slideOut {
      from { transform: translateX(0); opacity: 1; }
      to { transform: translateX(100%); opacity: 0; }
    }
    
    /* RTL support for specific languages */
    body[lang="ar"], body[lang="he"] {
      direction: rtl;
      text-align: right;
    }
    
    body[lang="ar"] .timeline:before,
    body[lang="he"] .timeline:before {
      right: 50%;
      left: auto;
    }
    
    /* Language-specific font adjustments */
    body.hindi, body.gujarati {
      font-family: "Arial", "Noto Sans", "Inter", sans-serif;
    }
  `;
  document.head.appendChild(style);
});

// Make it globally accessible
window.TranslationSystem = TranslationSystem;