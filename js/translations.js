// Translation functions
function applyLanguage(lang) {
  const elements = document.querySelectorAll("[data-i18n]");
  elements.forEach((element) => {
    const key = element.getAttribute("data-i18n");
    if (translations[lang] && translations[lang][key]) {
      if (
        element.tagName === "STRONG" ||
        element.tagName === "EM" ||
        element.hasAttribute("data-html")
      ) {
        element.innerHTML = translations[lang][key];
      } else {
        element.textContent = translations[lang][key];
      }
    }
  });

  // Update language display
  const currentLangElement = document.getElementById("currentLanguage");
  if (currentLangElement) {
    currentLangElement.textContent =
      lang === "en" ? "EN" : lang === "hi" ? "HI" : "GU";
  }

  // Update body class
  document.body.classList.remove("hindi", "gujarati");
  if (lang === "hi") document.body.classList.add("hindi");
  if (lang === "gu") document.body.classList.add("gujarati");

  // Save preference
  localStorage.setItem("preferredLanguage", lang);
}

// Initialize translation system
document.addEventListener("DOMContentLoaded", function () {
  // Load saved language or default to English
  let currentLang = localStorage.getItem("preferredLanguage") || "en";
  applyLanguage(currentLang);

  // Listen for language change events
  window.addEventListener("languageChange", function (e) {
    applyLanguage(e.detail.lang);

    // Show notification
    const messages = {
      en: "Language changed to English",
      hi: "भाषा हिंदी में बदल गई",
      gu: "ભાષા ગુજરાતીમાં બદલાઈ ગઈ",
    };

    // Create toast notification
    const toast = document.createElement("div");
    toast.className = "language-toast";
    toast.textContent = messages[e.detail.lang] || "Language changed";
    toast.style.cssText = `
            position: fixed;
            top: 100px;
            right: 20px;
            background: #0a2a4a;
            color: white;
            padding: 12px 20px;
            border-radius: 8px;
            box-shadow: 0 5px 15px rgba(0,0,0,0.2);
            z-index: 9999;
            animation: slideIn 0.3s ease;
        `;

    document.body.appendChild(toast);

    setTimeout(() => {
      toast.style.animation = "slideOut 0.3s ease";
      setTimeout(() => toast.remove(), 300);
    }, 3000);
  });

  // Add CSS for toast
  const style = document.createElement("style");
  style.textContent = `
        @keyframes slideIn {
            from { transform: translateX(100%); opacity: 0; }
            to { transform: translateX(0); opacity: 1; }
        }
        @keyframes slideOut {
            from { transform: translateX(0); opacity: 1; }
            to { transform: translateX(100%); opacity: 0; }
        }
    `;
  document.head.appendChild(style);
});
